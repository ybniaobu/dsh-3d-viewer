import { mkdir, readFile, stat, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const files = {
  nature: 'nature.hdr',
  city: 'city.hdr',
  indoor: 'indoor.hdr',
  studio: 'studio.hdr',
};

const targetPath = resolve(root, 'src', 'generated', 'hdri-data.js');
const scriptPath = fileURLToPath(import.meta.url);

async function mtime(path) {
  try {
    return (await stat(path)).mtimeMs;
  } catch {
    return 0;
  }
}

async function isUpToDate() {
  const targetInfo = await stat(targetPath).catch(() => null);
  if (targetInfo === null || targetInfo.size === 0) return false;

  const assets = Object.values(files).map((file) => resolve(root, 'assets', 'hdri', file));
  const newestSource = Math.max(await mtime(scriptPath), ...(await Promise.all(assets.map(mtime))));
  return targetInfo.mtimeMs >= newestSource;
}

/**
 * Embed the four CC0 HDRIs into a generated ES module.
 *
 * The generated module is reused when it is newer than every source asset, so
 * repeated builds do not re-read and re-encode ~8.7 MB of base64 text.
 *
 * @param {{ force?: boolean }} [options] Regenerate even when the cache is fresh.
 * @returns {Promise<boolean>} Whether the file was rewritten.
 */
export async function embedHdri({ force = false } = {}) {
  if (!force && await isUpToDate()) {
    console.log('Embedded HDRIs are up to date; skipped regeneration.');
    return false;
  }

  const entries = [];
  for (const [id, file] of Object.entries(files)) {
    const data = await readFile(resolve(root, 'assets', 'hdri', file));
    const dataUrl = `data:application/octet-stream;base64,${data.toString('base64')}`;
    entries.push(`  ${id}: ${JSON.stringify(dataUrl)},`);
  }

  const source = `// Generated by scripts/embed-hdri.mjs from assets/hdri/*.hdr. Do not edit.
// HDRIs are Poly Haven CC0 assets; see assets/hdri/LICENSE.md.
export const HDRI_DATA_URLS = {
${entries.join('\n')}
};
`;
  await mkdir(dirname(targetPath), { recursive: true });
  await writeFile(targetPath, source);
  console.log(`Embedded ${entries.length} HDRIs into src/generated/hdri-data.js.`);
  return true;
}

const invokedDirectly = process.argv[1] !== undefined
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) await embedHdri({ force: process.argv.includes('--force') });
